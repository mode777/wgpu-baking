// Regenerates THIRD_PARTY_NOTICES.md from `cargo metadata` and the extra entries below.
// Usage: node scripts/third-party-notices.mjs
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const extraPath = new URL("./third-party-extra.json", import.meta.url);
const extra = existsSync(extraPath) ? JSON.parse(readFileSync(extraPath, "utf8")) : [];

const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], { maxBuffer: 1 << 28 }).toString(),
);
const ours = new Set(meta.workspace_members);
const crates = meta.packages
  .filter((p) => !ours.has(p.id))
  .map((p) => ({ name: p.name, version: p.version, license: p.license ?? p.license_file ?? "UNKNOWN" }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const byLicense = new Map();
for (const c of crates) {
  if (!byLicense.has(c.license)) byLicense.set(c.license, []);
  byLicense.get(c.license).push(c);
}

let md = `# Third-party notices

wgpu-baking is MIT-licensed (see [LICENSE](LICENSE)). It includes or depends on the components below.
This file is generated by \`node scripts/third-party-notices.mjs\`; edit
\`scripts/third-party-extra.json\` for non-crate entries (upstream code, vendored sources, npm packages,
assets) and rerun it whenever \`Cargo.lock\` or a package manifest changes.

## Upstream, vendored and non-Rust components

| Component | Version | Licence | Source | Notes |
|---|---|---|---|---|
`;
for (const e of extra) md += `| ${e.name} | ${e.version} | ${e.license} | ${e.source} | ${e.notes ?? ""} |\n`;

md += `\n## Rust crates (${crates.length}, from Cargo.lock)\n\n`;
for (const [license, list] of [...byLicense].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))) {
  md += `### ${license} (${list.length})\n\n`;
  md += list.map((c) => `${c.name} ${c.version}`).join(", ") + "\n\n";
}
writeFileSync(new URL("../THIRD_PARTY_NOTICES.md", import.meta.url), md.trimEnd() + "\n");
console.log(`THIRD_PARTY_NOTICES.md: ${crates.length} crates, ${extra.length} extra entries`);
